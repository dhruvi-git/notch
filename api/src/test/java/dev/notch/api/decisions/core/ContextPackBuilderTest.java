package dev.notch.api.decisions.core;

import org.junit.jupiter.api.Test;

import java.time.Duration;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

class ContextPackBuilderTest {

    private static final Instant NOW = Instant.parse("2026-11-09T12:00:00Z");
    private final ContextPackBuilder builder = new ContextPackBuilder();

    private static DecisionItem decision(String title, int daysAgo, String... rejected) {
        return new DecisionItem(UUID.randomUUID(), title, null, List.of(rejected), NOW.minus(Duration.ofDays(daysAgo)), null, null);
    }

    private static TaskPrioritizer.Ranked task(String title) {
        return new TaskPrioritizer.Ranked(new TaskPrioritizer.Task(UUID.randomUUID(), title, NOW, null), 1);
    }

    private ContextPackBuilder.Input input() {
        return new ContextPackBuilder.Input("Billing service",
                List.of(decision("Use Postgres instead of MongoDB.", 10, "MongoDB"), decision("Use Stripe webhooks.", 2)),
                List.of(task("add idempotency keys")),
                List.of("Last session: Billing service: choosing a database (8 Nov)"),
                List.of(new ContextPackBuilder.Fix("Fix: ECONNREFUSED 5432", "Start Postgres with docker compose up -d", NOW)),
                NOW);
    }

    @Test
    void contextPackListsSectionsInPriorityOrder() {
        String md = builder.build(input(), ContextPackBuilder.Format.CONTEXT_PACK, 2000);
        assertTrue(md.startsWith("# Context: Billing service"));
        int d = md.indexOf("## Decisions in force"), t = md.indexOf("## Open tasks"),
                w = md.indexOf("## Where we stopped"), f = md.indexOf("## Known fixes");
        assertTrue(d > 0 && d < t && t < w && w < f);
        assertTrue(md.indexOf("Use Stripe webhooks") < md.indexOf("Use Postgres"));  // newest first
        assertTrue(md.contains("(decided 2026-10-30; rejected: MongoDB)"));
    }

    @Test
    void agentFilesTellTheAgentToFollowDecisions() {
        String agents = builder.build(input(), ContextPackBuilder.Format.AGENTS_MD, 2000);
        String claude = builder.build(input(), ContextPackBuilder.Format.CLAUDE_MD, 2000);
        assertTrue(agents.startsWith("# AGENTS.md"));
        assertTrue(claude.startsWith("# CLAUDE.md"));
        assertTrue(agents.contains("point out the conflict before writing code"));
        assertTrue(agents.contains("Generated by Notch on 2026-11-09"));
    }

    @Test
    void tightBudgetKeepsDecisionsAndDropsTheRest() {
        String md = builder.build(input(), ContextPackBuilder.Format.CONTEXT_PACK, 100);
        assertTrue(md.contains("## Decisions in force"));
        assertFalse(md.contains("## Known fixes"));
        assertTrue((md.length() + 3) / 4 <= 100);
    }

    @Test
    void agentFilesAreCappedInLines() {
        List<DecisionItem> many = new ArrayList<>();
        for (int i = 0; i < 400; i++) many.add(decision("Decision number " + i, i % 30));
        ContextPackBuilder.Input in = new ContextPackBuilder.Input("Big", many, List.of(), List.of(), List.of(), NOW);
        String md = builder.build(in, ContextPackBuilder.Format.CLAUDE_MD, 100_000);
        assertTrue(md.split("\n").length <= ContextPackBuilder.MAX_AGENT_FILE_LINES);
    }

    @Test
    void emptyProjectSaysSo() {  // boundary
        ContextPackBuilder.Input in = new ContextPackBuilder.Input("Empty", List.of(), List.of(), List.of(), List.of(), NOW);
        assertTrue(builder.build(in, ContextPackBuilder.Format.CONTEXT_PACK, 500).contains("Nothing recorded yet"));
        assertThrows(IllegalArgumentException.class, () -> builder.build(in, ContextPackBuilder.Format.CONTEXT_PACK, 10));
    }
}
