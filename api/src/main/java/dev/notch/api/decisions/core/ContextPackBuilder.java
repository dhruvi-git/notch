package dev.notch.api.decisions.core;

import java.time.Instant;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Locale;

/**
 * Writes a project's state as Markdown for a coding assistant: a context pack to paste into a
 * new chat, or an {@code AGENTS.md} / {@code CLAUDE.md} file the agent reads on its own.
 *
 * <p>Sections are filled in priority order (decisions, open tasks, where you stopped, recent
 * fixes) until the token budget runs out, so the most binding information always fits.
 * Agent files are also capped in lines, because agents load only the start of long files.
 */
public final class ContextPackBuilder {

    public enum Format { CONTEXT_PACK, AGENTS_MD, CLAUDE_MD }

    public record Fix(String title, String body, Instant at) {
    }

    public record Input(String projectName, List<DecisionItem> decisions, List<TaskPrioritizer.Ranked> tasks,
                        List<String> whereYouStopped, List<Fix> fixes, Instant now) {
        public Input {
            decisions = List.copyOf(decisions);
            tasks = List.copyOf(tasks);
            whereYouStopped = List.copyOf(whereYouStopped);
            fixes = List.copyOf(fixes);
        }
    }

    static final int MAX_AGENT_FILE_LINES = 150;
    static final int MAX_LINE_CHARS = 320;
    private static final DateTimeFormatter DAY = DateTimeFormatter.ofPattern("yyyy-MM-dd", Locale.ROOT)
            .withZone(ZoneOffset.UTC);

    public String build(Input in, Format format, int tokenBudget) {
        if (tokenBudget < 100) throw new IllegalArgumentException("tokenBudget must be at least 100");
        Writer w = new Writer(tokenBudget, format == Format.CONTEXT_PACK ? Integer.MAX_VALUE : MAX_AGENT_FILE_LINES);
        header(w, in, format);

        List<DecisionItem> decisions = new ArrayList<>(in.decisions());
        decisions.sort(Comparator.comparing(DecisionItem::decidedAt).reversed());
        if (!decisions.isEmpty() && w.section("## Decisions in force")) {
            for (DecisionItem d : decisions) {
                StringBuilder line = new StringBuilder("- ").append(oneLine(d.title()));
                List<String> extras = new ArrayList<>();
                extras.add("decided " + DAY.format(d.decidedAt()));
                if (!d.rejectedOptions().isEmpty()) extras.add("rejected: " + String.join(", ", d.rejectedOptions()));
                line.append(" (").append(String.join("; ", extras)).append(')');
                if (!w.line(line.toString())) break;
            }
        }
        if (!in.tasks().isEmpty() && w.section("## Open tasks")) {
            for (TaskPrioritizer.Ranked t : in.tasks()) if (!w.line("- " + oneLine(t.task().title()))) break;
        }
        if (!in.whereYouStopped().isEmpty() && w.section("## Where we stopped")) {
            for (String s : in.whereYouStopped()) if (!w.line("- " + oneLine(s))) break;
        }
        if (!in.fixes().isEmpty() && w.section("## Known fixes")) {
            for (Fix f : in.fixes()) {
                String body = f.body() == null ? "" : " → " + oneLine(f.body());
                if (!w.line("- " + oneLine(f.title()) + body)) break;
            }
        }
        if (w.empty()) w.forceLine("_Nothing recorded yet. Import a conversation to build this file._");
        return w.text();
    }

    private static void header(Writer w, Input in, Format format) {
        String generated = "Generated by Notch on " + DAY.format(in.now()) + ".";
        switch (format) {
            case CONTEXT_PACK -> {
                w.forceLine("# Context: " + in.projectName());
                w.forceLine("");
                w.forceLine("Here is where this project stands. Treat the decisions as settled unless I say otherwise.");
            }
            case AGENTS_MD, CLAUDE_MD -> {
                w.forceLine(format == Format.AGENTS_MD ? "# AGENTS.md" : "# CLAUDE.md");
                w.forceLine("");
                w.forceLine("<!-- " + generated + " Edit decisions in Notch; this file is regenerated. -->");
                w.forceLine("");
                w.forceLine("Project: " + in.projectName() + ". These decisions were made earlier in the project. "
                        + "Follow them unless the user says otherwise. If a request conflicts with one, point out "
                        + "the conflict before writing code.");
            }
        }
    }

    static String oneLine(String s) {
        String t = s == null ? "" : s.strip().replaceAll("\\s+", " ");
        return t.length() <= MAX_LINE_CHARS ? t : t.substring(0, MAX_LINE_CHARS - 1) + "…";
    }

    /** Appends lines while the token and line budgets allow. */
    private static final class Writer {
        private final StringBuilder sb = new StringBuilder();
        private final int tokenBudget;
        private final int maxLines;
        private int lines;
        private int bodyLines;
        private boolean full;  // once something did not fit, lower-priority sections are skipped

        Writer(int tokenBudget, int maxLines) {
            this.tokenBudget = tokenBudget;
            this.maxLines = maxLines;
        }

        private String pendingHeading;

        /** Starts a section. The heading is written only together with its first line. */
        boolean section(String heading) {
            if (full) return false;
            pendingHeading = heading;
            return true;
        }

        boolean line(String line) {
            String block = pendingHeading == null ? line : "\n" + pendingHeading + "\n" + line;
            if (full || !fits(block)) {
                full = true;
                pendingHeading = null;
                return false;
            }
            if (pendingHeading != null) {
                forceLine("");
                forceLine(pendingHeading);
                pendingHeading = null;
            }
            forceLine(line);
            bodyLines++;
            return true;
        }

        void forceLine(String line) {
            sb.append(line).append('\n');
            lines++;
        }

        private boolean fits(String more) {
            int tokens = (sb.length() + more.length() + 1 + 3) / 4;
            int newLines = (int) more.chars().filter(c -> c == '\n').count() + 1;
            return tokens <= tokenBudget && lines + newLines <= maxLines;
        }

        boolean empty() {
            return bodyLines == 0;
        }

        String text() {
            return sb.toString();
        }
    }
}
